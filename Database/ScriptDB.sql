GO
USE BankAtmPowerGridDB;
GO
CREATE TABLE AtmStation(
    MaTram NVARCHAR(20) PRIMARY KEY,
    DiaChi NVARCHAR(250) NOT NULL,
    TonQuy DECIMAL(18,2) NOT NULL CHECK(TonQuy >= 0),
    TrangThai NVARCHAR(40) NOT NULL,
    AnhHienTruong NVARCHAR(500) NULL
);
GO
CREATE TABLE AtmTransaction(
    MaGiaoDich BIGINT IDENTITY(1,1) PRIMARY KEY,
    MaTram NVARCHAR(20) NOT NULL REFERENCES AtmStation(MaTram),
    LoaiGiaoDich NVARCHAR(30) NOT NULL,
    SoTien DECIMAL(18,2) NOT NULL,
    ThoiGian DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    TrangThaiDoiSoat NVARCHAR(30) NOT NULL DEFAULT N'Chưa đối soát'
);
GO
CREATE TABLE GridLog(
    Id BIGINT IDENTITY(1,1) PRIMARY KEY,
    ThoiGian DATETIME2 NOT NULL,
    Tram NVARCHAR(100) NOT NULL,
    DienAp FLOAT NOT NULL,
    MucTai INT NOT NULL,
    CanhBao NVARCHAR(200) NOT NULL
);
GO
